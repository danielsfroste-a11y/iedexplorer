// Optional local FAT diagnostic, read-only MMS. Never invokes SendCommand, WriteData,
// a control service, configuration writes or a GOOSE publisher.
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Net;
using System.Text;
using System.Windows.Forms;
using IEDExplorer.Views;

namespace IEDExplorer
{
    internal static class ScadaMmsReadOnlyProbe
    {
        internal static int Run(string host)
        {
            IPAddress address;
            if (!IPAddress.TryParse(host, out address) ||
                address.AddressFamily != System.Net.Sockets.AddressFamily.InterNetwork)
            {
                File.WriteAllText("mms-probe-result.txt", "MMS PROBE ERROR: IPv4 address required.");
                return 2;
            }

            DateTime started = DateTime.UtcNow;
            DateTime requestedAt = DateTime.MinValue;
            List<ScadaBreakerBinding> breakers = new List<ScadaBreakerBinding>();
            int exitCode = 2;
            string result = "MMS connection was not established.";
            using (var window = new Views.MainWindow
            {
                WindowState = FormWindowState.Minimized,
                ShowInTaskbar = false,
                Opacity = 0
            })
            using (var tick = new Timer { Interval = 700 })
            {
                tick.Tick += delegate
                {
                    if (DateTime.UtcNow.Subtract(started).TotalSeconds > 35)
                    {
                        result = "MMS READ-ONLY PROBE TIMEOUT: " + host +
                            "; no IEC 61850 association/model completed within 35 seconds.";
                        tick.Stop();
                        window.Close();
                        return;
                    }
                    Iec61850State state = window.Get_iecf();
                    if (state == null || state.DataModel == null ||
                        state.istate != Iec61850lStateEnum.IEC61850_FREILAUF) return;
                    if (requestedAt == DateTime.MinValue)
                    {
                        NodeIed root = state.DataModel.ied;
                        foreach (NodeBase ld in root.GetChildNodes())
                            foreach (NodeBase ln in ld.GetChildNodes())
                            {
                                if (!ScadaBreakerBinding.IsBreakerLogicalNode(ln.Name)) continue;
                                var breaker = ScadaBreakerBinding.FromKey(ld.Name + "/" + ln.Name, root);
                                if (breaker != null && breakers.Count < 6) breakers.Add(breaker);
                            }
                        // For the first six breakers, issue only ordinary MMS Reads,
                        // which are the same requests generated by the existing watch view.
                        foreach (var data in breakers.SelectMany(x => x.MonitoredNodes()).Distinct().Take(24))
                            state.Controller.ReadData(data);
                        requestedAt = DateTime.UtcNow;
                        return;
                    }
                    if (DateTime.UtcNow.Subtract(requestedAt).TotalSeconds < 5) return;

                    var report = new StringBuilder();
                    report.AppendLine("MMS ASSOCIATION / MODEL READ: OK (read-only)");
                    report.AppendLine("Host: " + host);
                    report.AppendLine("IED Vendor: " + state.DataModel.ied.VendorName);
                    report.AppendLine("IED Model: " + state.DataModel.ied.ModelName);
                    report.AppendLine("Logical devices: " + string.Join(", ",
                        state.DataModel.ied.GetChildNodeNames().Take(20).ToArray()));
                    report.AppendLine("Switch objects discovered: " + breakers.Count);
                    foreach (var b in breakers)
                    {
                        report.AppendLine("  Switch: " + b.Key);
                        report.AppendLine("    Status: " + b.StatusAddress);
                        report.AppendLine("    Pos.stVal: " +
                            (b.Position == null || b.Position.DataValue == null ? "<not read>" :
                             b.Position.DataValue is byte[] ? BitConverter.ToString((byte[])b.Position.DataValue) :
                             b.Position.DataValue.ToString()));
                        report.AppendLine("    Status type / trailing bits: " +
                            (b.Position == null ? "<missing>" : b.Position.DataType.ToString() + " / " +
                             (b.Position.DataParam == null ? "<unknown>" : b.Position.DataParam.ToString())));
                        report.AppendLine("    Oper type / trailing bits: " +
                            (b.Operate == null ? "<missing>" : b.Operate.DataType.ToString() + " / " +
                             (b.Operate.DataParam == null ? "<unknown>" : b.Operate.DataParam.ToString())));
                        report.AppendLine("    Decoded: " + b.PositionValue);
                        report.AppendLine("    " + b.QualitySummary);
                        report.AppendLine("    Control model: " + b.ControlModelValue + " (" + b.ControlSummary + ")");
                        report.AppendLine("    Oper.ctlVal present: " + (b.Operate != null));
                        report.AppendLine("    SBOw.ctlVal present: " + (b.SelectWithValue != null));
                        report.AppendLine("    Source time: " + (b.Timestamp == null ? "<missing>" :
                            b.Timestamp.DataValue == null ? "<not read>" : b.Timestamp.StringValue));
                    }
                    report.AppendLine("NO COMMANDS, SETTINGS WRITES OR GOOSE TRANSMISSIONS SENT.");
                    result = report.ToString();
                    exitCode = 0;
                    tick.Stop();
                    window.Close();
                };
                window.Shown += delegate
                {
                    window.BeginReadOnlyProbe(host);
                    tick.Start();
                };
                Application.Run(window);
            }
            File.WriteAllText("mms-probe-result.txt", result);
            return exitCode;
        }
    }
}
